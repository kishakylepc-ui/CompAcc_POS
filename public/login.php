<script>

/* =========================================================
   SHOW / HIDE PASSWORD
========================================================= */

const passwordInput =
    document.getElementById('password');

const showPassword =
    document.getElementById('showPassword');

const passwordIcon =
    document.getElementById('passwordIcon');


showPassword.addEventListener(
    'click',
    function () {

        const isPassword =
            passwordInput.type === 'password';


        passwordInput.type =
            isPassword
                ? 'text'
                : 'password';


        passwordIcon.textContent =
            isPassword
                ? 'visibility_off'
                : 'visibility';


        showPassword.setAttribute(
            'aria-label',
            isPassword
                ? 'Hide password'
                : 'Show password'
        );

    }
);


/* =========================================================
   FORGOT PASSWORD WINDOW
========================================================= */

const forgotModal =
    document.getElementById('forgotModal');

const forgotUsername =
    document.getElementById('forgotUsername');

const loginUsername =
    document.getElementById('username');

const forgotLink =
    document.getElementById('openForgotPassword');


function openForgotPassword() {

    /* Start from what was typed in the sign-in form. */
    if (
        forgotUsername.value.trim() === '' &&
        loginUsername
    ) {
        forgotUsername.value = loginUsername.value.trim();
    }

    forgotModal.hidden = false;

    forgotUsername.focus();
}


function closeForgotPassword() {

    forgotModal.hidden = true;

    /* Back to the link, for keyboard users. */
    forgotLink.focus();
}


forgotLink
    .addEventListener(
        'click',
        function (event) {
            event.preventDefault();
            openForgotPassword();
        }
    );


forgotModal
    .querySelectorAll('[data-forgot-close]')
    .forEach(
        element => element.addEventListener(
            'click',
            closeForgotPassword
        )
    );


document.addEventListener(
    'keydown',
    function (event) {

        if (
            event.key !== 'Escape' ||
            forgotModal.hidden ||
            window.UA?.isConfirmOpen?.()
        ) {
            return;
        }

        closeForgotPassword();
    }
);


/* Opened again after "Enter your username". */
if (!forgotModal.hidden) {
    forgotUsername.focus();
}

</script>


